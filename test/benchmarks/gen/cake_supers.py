#!/usr/bin/env python3
"""Generates CakeSupersBenchmark.scala: cakes of N self-typed traits, as in scala.reflect.internal.SymbolTable.

python3 test/benchmarks/gen/cake_supers.py > test/benchmarks/src/main/scala/scala/tools/nsc/CakeSupersBenchmark.scala
"""
SIZES = [30, 60, 70, 100]
CLASSES = 8
CALLS = 8

out = []
w = out.append
w("""// Generated by test/benchmarks/gen/cake_supers.py; do not edit.
package scala.tools.nsc

import java.util.concurrent.TimeUnit

import org.openjdk.jmh.annotations._

/** The cost of calls between the traits of a cake, as in `scala.reflect.internal.SymbolTable`, by the number of
 *  traits (the class's secondary supers) and the number of concrete classes the call sites see.
 *
 *  In a trait `T` with self type `U` (a class), an unqualified call to a member of another trait `T2` of the cake is
 *  compiled as `checkcast T2; invokeinterface T2.m` on `this` (`viaTrait`). The cast checks `U`'s secondary supers:
 *  JDK 23+ keeps them in a 63-slot hashed table, so beyond 62 interfaces it is full and a miss takes a linear scan;
 *  before, a one-element cache that thrashes when the cast alternates between interfaces. C2 skips the check when the
 *  cast's type profile shows one class, so the cost appears once several classes share the code (`classes` > 1), as
 *  when Scaladoc, the presentation compiler or macro toolboxes run beside the compiler. `viaClass` makes the same
 *  calls through `this.asInstanceOf[U]`: `checkcast U` (a primary supers check) and `invokevirtual`.
 *
 *  `Hot`'s methods are not inlined (`-XX:CompileCommand=dontinline`), as the compiler's hot trait methods are too big
 *  to be: inlined into a caller whose receiver is known to be a `U`, C2 would fold the casts away.
 */
@BenchmarkMode(Array(Mode.AverageTime))
@Fork(value = 1, jvmArgsAppend = Array("-Xms1G", "-Xmx1G", "-XX:CompileCommand=quiet", "-XX:CompileCommand=dontinline,*$Hot::via*"))
@Threads(1)
@Warmup(iterations = 10, time = 1)
@Measurement(iterations = 10, time = 1)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@State(Scope.Benchmark)
class CakeSupersBenchmark {
  import CakeSupersBenchmark._

  /** The number of traits in the cake, so its classes' secondary supers (plus one, `Hot`). */
  @Param(Array(%s))
  var traits: Int = _

  /** How many concrete classes of the cake the receivers are drawn from (1 to %d). */
  @Param(Array("1", "4"))
  var classes: Int = _

  private var receivers: Array[Root] = _

  @Setup(Level.Trial) def setup(): Unit = {
    val random = new java.util.SplittableRandom(1)
    receivers = Array.fill(Receivers)(make(traits, random.nextInt(classes)))
  }

  /** One op is one call; each call makes %d calls to other traits of the cake. */
  @Benchmark @OperationsPerInvocation(Receivers)
  def viaTrait(): Int = {
    val rs = receivers
    var sum = 0
    var i = 0
    while (i < rs.length) { sum += rs(i).viaTrait(i); i += 1 }
    sum
  }

  @Benchmark @OperationsPerInvocation(Receivers)
  def viaClass(): Int = {
    val rs = receivers
    var sum = 0
    var i = 0
    while (i < rs.length) { sum += rs(i).viaClass(i); i += 1 }
    sum
  }
}

object CakeSupersBenchmark {
  final val Receivers = 1024

  abstract class Root {
    def viaTrait(x: Int): Int
    def viaClass(x: Int): Int
  }

  def make(traits: Int, cls: Int): Root = traits match {
%s
  }
""" % (", ".join('"%d"' % n for n in SIZES), CLASSES, CALLS,
       "\n".join("    case %d => Cake%d.make(cls)" % (n, n) for n in SIZES)))

for n in SIZES:
    called = [1 + (k * (n - 1)) // (CALLS - 1) for k in range(CALLS)]  # spread over the cake, first to last
    w("\n  object Cake%d {" % n)
    w("    abstract class U extends Root\n" + "".join("      with T%d\n" % i for i in range(1, n + 1)) + "      with Hot")
    for i in range(1, n + 1):
        w("    trait T%d { self: U => def f%d(x: Int): Int = x + %d }" % (i, i, i))
    w("    trait Hot { self: U =>")
    w("      def viaTrait(x: Int): Int = " + " ^ ".join("f%d(x)" % i for i in called))
    w("      def viaClass(x: Int): Int = { val u = this.asInstanceOf[U]; " + " ^ ".join("u.f%d(x)" % i for i in called) + " }")
    w("    }")
    for c in range(CLASSES):
        w("    final class C%d extends U" % c)
    w("    def make(cls: Int): Root = cls match {")
    for c in range(CLASSES):
        w("      case %d => new C%d" % (c, c))
    w("    }")
    w("  }")
w("}")
print("\n".join(out))
